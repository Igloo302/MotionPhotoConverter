import Foundation

enum Language: String {
    case english = "en"
    case chinese = "zh"
    case french = "fr"
    case german = "de"
    case spanish = "es"
    case japanese = "ja"
    case korean = "ko"
    
    static var current: Language {
        let preferredLanguage = Locale.preferredLanguages.first ?? "en"
        let languageCode = String(preferredLanguage.prefix(2))
        return Language(rawValue: languageCode) ?? .english
    }
}

struct Localizable {
    static func string(_ key: LocalizableKey) -> String {
        switch Language.current {
        case .english:
            return key.english
        case .chinese:
            return key.chinese
        case .french:
            return key.french
        case .german:
            return key.german
        case .spanish:
            return key.spanish
        case .japanese:
            return key.japanese
        case .korean:
            return key.korean
        }
    }
    
    static func string(_ key: LocalizableKey, _ args: CVarArg...) -> String {
        let format = string(key)
        return String(format: format, arguments: args)
    }
}

